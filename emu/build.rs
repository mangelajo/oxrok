//! Generates the model registry from the files in `src/models`.
//!
//! Every `src/models/NAME.rs` and `src/models/NAME/mod.rs` is a model
//! (`mod.rs` of the directory itself excluded, and entries starting
//! with `.`, such as editors' lock and swap files, skipped). A model
//! with submodules is a directory, `NAME/mod.rs` next to `NAME/sub.rs`:
//! the `#[path]` declaration makes rustc look for the submodules of a
//! `NAME.rs` next to it rather than in `NAME/`, so `NAME.rs` and a
//! directory `NAME` side by side are refused. The generated file,
//! included by `src/models/mod.rs`, declares each as a module (a name
//! with `-` becomes an identifier with `_`) and builds the `NAMES`
//! table and the `build` dispatch from the `NAME`, `ABOUT` and `build`
//! each module exports, and the `log_rules` dispatch from the modules
//! with a line that starts `pub fn log_rules(`. A new model is a new
//! file and nothing else, so models written in parallel never touch a
//! shared list.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Words a module cannot be named: Rust's keywords, and `tests`, the
/// unit test module of `src/models/mod.rs`.
const KEYWORDS: &[&str] = &[
    "tests", "as", "async", "await", "box", "break", "const", "continue", "crate", "dyn", "else",
    "enum", "extern", "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match",
    "mod", "move", "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait",
    "true", "try", "type", "unsafe", "use", "where", "while", "yield",
];

/// The models on vusb so far; the move goes shell by shell.
const MIGRATED: &[&str] = &["usbrelay", "ftdi-la", "fx2lafw"];

/// The module identifier of a model file name.
fn ident(name: &str) -> String {
    assert!(
        !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_'),
        "emu/src/models/{name}: a model name is letters, digits, '-' and '_'"
    );
    let id = name.replace('-', "_").to_ascii_lowercase();
    if id.starts_with(|c: char| c.is_ascii_digit()) || KEYWORDS.contains(&id.as_str()) {
        format!("model_{id}")
    } else {
        id
    }
}

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
        .join("src")
        .join("models");
    println!("cargo:rerun-if-changed={}", dir.display());

    // identifier -> (model name, path)
    let mut models: BTreeMap<String, (String, PathBuf)> = BTreeMap::new();
    let entries = fs::read_dir(&dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display()));
    for entry in entries {
        let entry = entry.expect("models directory entry");
        let path = entry.path();
        let file = entry.file_name().to_string_lossy().into_owned();
        if file.starts_with('.') {
            continue;
        }
        let (name, source) = if path.is_dir() {
            let m = path.join("mod.rs");
            if !m.is_file() {
                continue;
            }
            (file, m)
        } else if let Some(stem) = file.strip_suffix(".rs") {
            if stem == "mod" {
                continue;
            }
            assert!(
                !dir.join(stem).is_dir(),
                "emu/src/models/{stem}.rs and the directory {stem}/: a model with submodules is \
                 {stem}/mod.rs, the submodules beside it in {stem}/"
            );
            (stem.to_owned(), path.clone())
        } else {
            continue;
        };
        if !MIGRATED.contains(&name.as_str()) {
            continue;
        }
        let id = ident(&name);
        if let Some((other, _)) = models.get(&id) {
            panic!("emu/src/models: {name} and {other} map to the same module {id}");
        }
        models.insert(id, (name, source));
    }

    let mut out =
        String::from("// Generated by emu/build.rs from the files in emu/src/models.\n\n");
    for (id, (_, path)) in &models {
        writeln!(out, "#[path = {:?}]\npub mod {id};", path_str(path)).unwrap();
    }
    out.push_str("\n/// Name and description of each model, with its options, by name.\n");
    out.push_str("pub const NAMES: &[(&str, &str)] = &[\n");
    for id in models.keys() {
        writeln!(out, "    ({id}::NAME, {id}::ABOUT),").unwrap();
    }
    out.push_str("];\n\n/// The file name each model comes from, in the order of [`NAMES`].\n");
    out.push_str("pub const FILES: &[&str] = &[\n");
    for (name, _) in models.values() {
        writeln!(out, "    {name:?},").unwrap();
    }
    out.push_str("];\n\n");
    out.push_str(
        "/// Builds a model from its name and `key=value` options.\n\
         ///\n\
         /// # Errors\n\
         ///\n\
         /// When no model has that name, or the model rejects an option.\n\
         pub fn build(name: &str, options: &[(String, String)]) -> Result<Box<dyn DeviceModel>> {\n",
    );
    for id in models.keys() {
        writeln!(out, "    if name == {id}::NAME {{\n        return {id}::build(options);\n    }}")
            .unwrap();
    }
    out.push_str(
        "    Err(Error::Invalid(format!(\"no model named {name}; oxrok-emu list names them\")))\n}\n\n",
    );
    out.push_str(
        "/// How the transaction log shows a model built with `options`.\n\
         pub fn log_rules(name: &str, options: &[(String, String)]) -> crate::txlog::Rules {\n",
    );
    for (id, (_, path)) in &models {
        let source = fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        if source.lines().any(|l| l.starts_with("pub fn log_rules(")) {
            writeln!(
                out,
                "    if name == {id}::NAME {{\n        return {id}::log_rules(options);\n    }}"
            )
            .unwrap();
        }
    }
    out.push_str("    let _ = (name, options);\n    crate::txlog::Rules::default()\n}\n");

    let dest = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("models.rs");
    // Rewritten only when it changes, so an unrelated build script run
    // does not recompile the crate.
    if fs::read_to_string(&dest).ok().as_deref() != Some(out.as_str()) {
        fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
    }
}

fn path_str(path: &Path) -> String {
    path.to_str().unwrap_or_else(|| panic!("{}: not UTF-8", path.display())).to_owned()
}
